const mongoose = require('mongoose');

const diamondSchema = new mongoose.Schema({
    type_id: {
        type: String,
        required: true
    },
    type_name: {
        type: String
        // Optional - derived from type_id on display if missing
    },
    source: {
        type: String,
        enum: ['real', 'cvd'],
        required: true
    },
    source_name: {
        type: String
        // Optional - derived from source on display if missing
    },
    weight_ct: {
        type: Number,
        required: true,
        min: [0.01, 'Diamond weight must be positive'],
        max: [100, 'Diamond weight exceeds maximum']
    }
}, { _id: false });

// Polki/Stone schema for Polki jewelry articles
const polkiStoneSchema = new mongoose.Schema({
    type_id: {
        type: String,
        required: true,
        enum: ['stone', 'polki']
    },
    type_name: {
        type: String
        // Optional - derived from type_id on display if missing
    },
    weight_ct: {
        type: Number,
        required: true,
        min: [0.01, 'Polki/Stone weight must be positive'],
        max: [100, 'Polki/Stone weight exceeds maximum']
    }
}, { _id: false });

const itemSchema = new mongoose.Schema({
    sku: {
        type: String,
        required: [true, 'SKU is required'],
        unique: true,
        uppercase: true,
        index: true
    },
    name: {
        type: String,
        trim: true,
        maxlength: 200
    },
    // Article type: 'diamond' or 'polki'
    articleType: {
        type: String,
        enum: ['diamond', 'polki'],
        default: 'diamond'
    },
    category: {
        id: {
            type: String,
            required: true
        },
        name: {
            type: String,
            required: true
        },
        prefix: {
            type: String,
            required: true,
            maxlength: 4
        }
    },
    gold: {
        purity: {
            type: String,
            enum: ['14K', '18K', '22K', '24K'],
            required: [true, 'Gold purity is required']
        },
        weight_g: {
            type: Number,
            required: [true, 'Gold weight is required'],
            min: [0.01, 'Gold weight must be positive'],
            max: [10000, 'Gold weight exceeds maximum']
        }
    },
    diamonds: [diamondSchema],
    polkiStones: [polkiStoneSchema],
    qrData: {
        type: String
        // Auto-generated by pre-save hook, not required in request
    },
    createdBy: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: true
    },
    updatedBy: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User'
    },
    // Soft delete fields
    deletedAt: {
        type: Date,
        default: null
    },
    deletedBy: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        default: null
    },
    // Image references (paths only, not binary data)
    images: {
        primary: { type: String, default: null },
        gallery: [{ type: String }]
    },

    // ============ MODULAR ARCHITECTURE FIELDS (v1.4.0) ============

    // Reference to ItemMaster (nullable for legacy items)
    itemMasterId: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'ItemMaster',
        default: null
    },

    // Dynamic attributes (validated against schema)
    attributes: {
        type: Map,
        of: mongoose.Schema.Types.Mixed,
        default: new Map()
    },

    // Pricing computation metadata
    pricing: {
        pricingRuleId: {
            type: mongoose.Schema.Types.ObjectId,
            ref: 'PricingRule'
        },
        pricingRuleVersion: Number,
        rateTableId: {
            type: mongoose.Schema.Types.ObjectId,
            ref: 'RateTable'
        },
        rateTableVersion: Number,
        lastComputedAt: Date,
        lastComputedBreakdown: {
            type: mongoose.Schema.Types.Mixed,
            default: null
        }
    }
}, {
    timestamps: true
});

// Pre-save hook: Store only SKU in qrData for smaller QR codes
// Item details are fetched from database on scan
itemSchema.pre('save', function (next) {
    this.qrData = this.sku;
    next();
});

// Exclude soft-deleted items by default
itemSchema.pre(/^find/, function (next) {
    // Skip if explicitly querying deleted items
    if (this.getQuery().deletedAt !== undefined) {
        return next();
    }
    this.where({ deletedAt: null });
    next();
});

// Index for faster queries
itemSchema.index({ 'category.id': 1 });
itemSchema.index({ createdAt: -1 });
itemSchema.index({ deletedAt: 1 });
// PERF: Compound index for dashboard stats (deletedAt + createdAt)
itemSchema.index({ deletedAt: 1, createdAt: -1 });
// PERF: Index for gold weight aggregation
itemSchema.index({ deletedAt: 1, 'gold.weight_g': 1 });
// PERF: Index for category aggregation
itemSchema.index({ deletedAt: 1, 'category.name': 1 });
// PERF: Index for diamond type usage checks
itemSchema.index({ deletedAt: 1, 'diamonds.type_id': 1 });

module.exports = mongoose.model('Item', itemSchema);

