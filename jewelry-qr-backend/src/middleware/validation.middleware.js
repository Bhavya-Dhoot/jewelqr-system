const Joi = require('joi');

/**
 * Validation middleware factory
 * @param {Joi.Schema} schema - Joi validation schema
 * @param {string} property - Request property to validate ('body', 'query', 'params')
 */
const validate = (schema, property = 'body') => {
    return (req, res, next) => {
        const { error, value } = schema.validate(req[property], {
            abortEarly: false,
            stripUnknown: true
        });

        if (error) {
            const errors = error.details.map(detail => ({
                field: detail.path.join('.'),
                message: detail.message
            }));

            return res.status(400).json({
                success: false,
                message: 'Validation failed',
                errors
            });
        }

        // Replace with validated/sanitized value
        req[property] = value;
        next();
    };
};

// ============ Validation Schemas ============

// Auth schemas
const loginSchema = Joi.object({
    username: Joi.string().required().min(3).max(50),
    password: Joi.string().required().min(6)
});

// Item schemas - SKU is server-generated, qrData is auto-generated by pre-save hook
const createItemSchema = Joi.object({
    sku: Joi.string().uppercase().pattern(/^[A-Z]{3}-[A-Z0-9]{6}$/), // Optional, will be overwritten by server
    name: Joi.string().allow('').max(200),
    // Article type: diamond or polki jewelry
    articleType: Joi.string().valid('diamond', 'polki').default('diamond'),
    category: Joi.object({
        id: Joi.string().required(),
        name: Joi.string().required(),
        prefix: Joi.string().required().length(3)
    }).required(),
    gold: Joi.object({
        purity: Joi.string().required().valid('14K', '18K', '22K', '24K'),
        weight_g: Joi.number().required().positive().max(10000)
    }).required(),
    diamonds: Joi.array().items(
        Joi.object({
            type_id: Joi.string().required(),
            type_name: Joi.string().required(),
            source: Joi.string().required().valid('real', 'cvd'),
            source_name: Joi.string().required(),
            weight_ct: Joi.number().required().positive().max(100)
        })
    ).max(6),
    // Polki/Stone entries for polki article type
    polkiStones: Joi.array().items(
        Joi.object({
            type_id: Joi.string().required().valid('stone', 'polki'),
            type_name: Joi.string(),
            source: Joi.string().valid('real', 'cvd'),
            source_name: Joi.string(),
            weight_ct: Joi.number().required().positive().max(100)
        })
    ).max(6),
    qrData: Joi.string() // Optional, auto-generated by pre-save hook
});

// Update item schema (all fields optional, but at least one required)
const updateItemSchema = Joi.object({
    name: Joi.string().allow('').max(200),
    articleType: Joi.string().valid('diamond', 'polki'),
    category: Joi.object({
        id: Joi.string().required(),
        name: Joi.string().required(),
        prefix: Joi.string().required().length(3)
    }),
    gold: Joi.object({
        purity: Joi.string().required().valid('14K', '18K', '22K', '24K'),
        weight_g: Joi.number().required().positive().max(10000)
    }),
    diamonds: Joi.array().items(
        Joi.object({
            type_id: Joi.string().required(),
            type_name: Joi.string().required(),
            source: Joi.string().required().valid('real', 'cvd'),
            source_name: Joi.string().required(),
            weight_ct: Joi.number().required().positive().max(100)
        })
    ).max(6),
    polkiStones: Joi.array().items(
        Joi.object({
            type_id: Joi.string().required().valid('stone', 'polki'),
            type_name: Joi.string(),
            source: Joi.string().valid('real', 'cvd'),
            source_name: Joi.string(),
            weight_ct: Joi.number().required().positive().max(100)
        })
    ).max(6)
}).min(1); // Require at least one field

// Settings schemas
const updateRatesSchema = Joi.object({
    goldRate: Joi.number().positive(),
    diamondRate: Joi.number().positive(),
    cvdDiamondRate: Joi.number().positive(),
    makingCharges: Joi.number().min(0),
    taxPercent: Joi.number().min(0).max(100)
});

const addDiamondTypeSchema = Joi.object({
    id: Joi.string().min(2).max(50),
    label: Joi.string().min(2).max(50),
    name: Joi.string().min(2).max(50),  // Legacy support
    realRate: Joi.number().positive().default(50000),
    cvdRate: Joi.number().positive().default(25000),
    rateMultiplier: Joi.number().positive().default(1.0)
}).or('id', 'label', 'name');  // At least one identifier required

module.exports = {
    validate,
    schemas: {
        loginSchema,
        createItemSchema,
        updateItemSchema,
        updateRatesSchema,
        addDiamondTypeSchema
    }
};
