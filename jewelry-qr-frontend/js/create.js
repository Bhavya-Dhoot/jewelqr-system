/**
 * Setup image upload event listeners
 */
function setupImageUploadListeners() {
  const primaryInput = document.getElementById('primaryImage');
  const galleryInput = document.getElementById('galleryImages');
  const removePrimaryBtn = document.getElementById('removePrimary');

  if (primaryInput) {
    primaryInput.addEventListener('change', handlePrimaryImageSelect);
  }

  if (galleryInput) {
    galleryInput.addEventListener('change', handleGalleryImagesSelect);
  }

  if (removePrimaryBtn) {
    removePrimaryBtn.addEventListener('click', removePrimaryImage);
  }
}

/**
 * Handle primary image selection
 */
function handlePrimaryImageSelect(e) {
  const file = e.target.files[0];
  if (!file) return;

  // Validate file size (5MB max)
  if (file.size > 5 * 1024 * 1024) {
    showToast('Image must be less than 5MB', 'error');
    e.target.value = '';
    return;
  }

  selectedPrimaryImage = file;

  // Show preview
  const reader = new FileReader();
  reader.onload = (event) => {
    const previewImg = document.getElementById('primaryPreviewImg');
    const previewDiv = document.getElementById('primaryPreview');
    const label = document.getElementById('primaryLabel');
    const box = document.getElementById('primaryUploadBox');

    previewImg.src = event.target.result;
    previewDiv.classList.remove('hidden');
    label.classList.add('hidden');
    box.classList.add('has-image');
  };
  reader.readAsDataURL(file);
}

/**
 * Remove primary image
 */
function removePrimaryImage() {
  selectedPrimaryImage = null;

  const previewDiv = document.getElementById('primaryPreview');
  const label = document.getElementById('primaryLabel');
  const box = document.getElementById('primaryUploadBox');
  const input = document.getElementById('primaryImage');

  previewDiv.classList.add('hidden');
  label.classList.remove('hidden');
  box.classList.remove('has-image');
  input.value = '';
}

/**
 * Handle gallery images selection
 */
function handleGalleryImagesSelect(e) {
  const files = Array.from(e.target.files);

  // Check max gallery images (6)
  if (selectedGalleryImages.length + files.length > 6) {
    showToast('Maximum 6 gallery images allowed', 'warning');
    e.target.value = '';
    return;
  }

  // Validate each file
  for (const file of files) {
    if (file.size > 5 * 1024 * 1024) {
      showToast(`${file.name} exceeds 5MB limit`, 'error');
      continue;
    }
    selectedGalleryImages.push(file);
    addGalleryPreview(file, selectedGalleryImages.length - 1);
  }

  e.target.value = ''; // Reset input to allow same file selection
}

/**
 * Add gallery preview thumbnail
 */
function addGalleryPreview(file, index) {
  const container = document.getElementById('galleryPreviews');

  const reader = new FileReader();
  reader.onload = (event) => {
    const item = document.createElement('div');
    item.className = 'gallery-preview-item';
    item.dataset.index = index;
    item.innerHTML = `
      <img src="${event.target.result}" alt="Gallery preview">
      <button type="button" class="preview-remove" aria-label="Remove image">
        <svg width="12" height="12" viewBox="0 0 16 16" fill="none">
          <path d="M12 4L4 12M4 4l8 8" stroke="currentColor" stroke-width="2" stroke-linecap="round"/>
        </svg>
      </button>
    `;

    item.querySelector('.preview-remove').addEventListener('click', () => {
      removeGalleryImage(index);
      item.remove();
    });

    container.appendChild(item);
  };
  reader.readAsDataURL(file);
}

/**
 * Remove gallery image
 */
function removeGalleryImage(index) {
  selectedGalleryImages[index] = null; // Mark as removed, keep indices stable
}

/**
 * Upload images after item creation
 */
async function uploadImages(sku) {
  const formData = new FormData();
  let hasImages = false;

  // Add primary image
  if (selectedPrimaryImage) {
    formData.append('primary', selectedPrimaryImage);
    hasImages = true;
  }

  // Add gallery images (filter out removed ones)
  selectedGalleryImages.filter(f => f !== null).forEach(file => {
    formData.append('gallery', file);
    hasImages = true;
  });

  if (!hasImages) return;

  try {
    showToast('Uploading images...', 'info');
    const response = await api.uploadItemImages(sku, formData);

    if (response.success) {
      showToast('Images uploaded successfully!', 'success');
    } else {
      showToast('Image upload failed: ' + response.message, 'warning');
    }
  } catch (error) {
    console.error('Image upload error:', error);
    showToast('Image upload failed (item still saved)', 'warning');
  }

  // Reset image state
  selectedPrimaryImage = null;
  selectedGalleryImages = [];
}

/**
 * Reset image state (called on form reset)
 */
function resetImageState() {
  selectedPrimaryImage = null;
  selectedGalleryImages = [];

  // Reset primary preview
  const previewDiv = document.getElementById('primaryPreview');
  const label = document.getElementById('primaryLabel');
  const box = document.getElementById('primaryUploadBox');
  const input = document.getElementById('primaryImage');

  if (previewDiv) previewDiv.classList.add('hidden');
  if (label) label.classList.remove('hidden');
  if (box) box.classList.remove('has-image');
  if (input) input.value = '';

  // Clear gallery previews
  const galleryPreviews = document.getElementById('galleryPreviews');
  if (galleryPreviews) galleryPreviews.innerHTML = '';

  const galleryInput = document.getElementById('galleryImages');
  if (galleryInput) galleryInput.value = '';
}

