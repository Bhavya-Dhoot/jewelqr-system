/**
 * Simple hash function (djb2 algorithm)
 * Creates a consistent hash from any string input
 */
function hashString(str) {
  let hash = 5381;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = ((hash << 5) + hash) + char; // hash * 33 + char
  }
  return Math.abs(hash);
}

/**
 * Generate unique ID using timestamp + random component
 * This ensures uniqueness even for items with the same name
 */
function generateUniqueHash() {
  const timestamp = Date.now();
  const randomPart = Math.random().toString(36).substring(2, 8);
  const sessionPart = Math.random().toString(36).substring(2, 6);

  // Combine timestamp, random, and session for uniqueness
  const combined = `${timestamp}-${randomPart}-${sessionPart}`;
  const hash = hashString(combined);

  // Convert to 6-digit alphanumeric
  return hash.toString(36).toUpperCase().substring(0, 6).padStart(6, '0');
}

/**
 * Show SKU placeholder - actual SKU is generated by backend
 * The backend uses an atomic counter for guaranteed unique sequential SKUs
 */
function generateNewSKU() {
  const categorySelect = document.getElementById('jewelryCategory');
  const categoryId = categorySelect ? categorySelect.value : '';

  // Get prefix from config or use fallback
  let prefix = 'OTH'; // Default fallback
  if (categoryId && typeof config !== 'undefined') {
    const category = config.getJewelryCategoryById(categoryId);
    if (category) {
      prefix = category.prefix;
    }
  } else if (categoryId) {
    // Fallback prefixes if config not loaded
    const prefixes = {
      chain: 'CHN', bangles: 'BNG', earrings: 'EAR',
      necklace: 'NCK', pendant_set: 'PND', others: 'OTH'
    };
    prefix = prefixes[categoryId] || 'OTH';
  }

  // Show placeholder with prefix - actual SKU generated by backend
  const placeholder = `${prefix}-XXXXXX`;
  document.getElementById('skuValue').textContent = placeholder;
  document.getElementById('qrSkuDisplay').textContent = 'Generated after save';

  return placeholder;
}


