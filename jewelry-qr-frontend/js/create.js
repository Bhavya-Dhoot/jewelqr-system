/**
 * Validate gold purity
 */
function validatePurity() {
  const purity = document.getElementById('goldPurity');
  const error = document.getElementById('purityError');

  if (!purity.value) {
    purity.classList.add('error');
    error.classList.remove('hidden');
    return false;
  } else {
    purity.classList.remove('error');
    purity.classList.add('success');
    error.classList.add('hidden');
    return true;
  }
}

/**
 * Validate gold weight
 */
function validateWeight() {
  const weight = document.getElementById('goldWeight');
  const error = document.getElementById('weightError');
  const value = parseFloat(weight.value);

  if (!value || value <= 0) {
    weight.classList.add('error');
    error.classList.remove('hidden');
    return false;
  } else {
    weight.classList.remove('error');
    weight.classList.add('success');
    error.classList.add('hidden');
    return true;
  }
}

/**
 * Validate entire form
 */
function validateForm() {
  let isValid = true;

  // Validate category
  if (!validateCategory()) isValid = false;

  // Validate purity
  if (!validatePurity()) isValid = false;

  // Validate weight
  if (!validateWeight()) isValid = false;

  // Validate diamonds (always diamond mode now)
  const diamondRows = document.querySelectorAll('#diamondSection .diamond-row');
  diamondRows.forEach(row => {
    const type = row.querySelector('.diamond-type');
    const weight = row.querySelector('.diamond-weight');

    if (!type.value) {
      type.classList.add('error');
      isValid = false;
    } else {
      type.classList.remove('error');
      type.classList.add('success');
    }

    if (!weight.value || parseFloat(weight.value) <= 0) {
      weight.classList.add('error');
      isValid = false;
    } else {
      weight.classList.remove('error');
      weight.classList.add('success');
    }
  });

  return isValid;
}

/**
 * Handle form submission
 */
async function handleFormSubmit(e) {
  e.preventDefault();

  if (!validateForm()) {
    showToast('Please fix errors before generating QR', 'error');
    return;
  }

  const submitBtn = document.getElementById('submitBtn');
  submitBtn.classList.add('loading');
  submitBtn.disabled = true;

  try {
    // Collect form data
    const formData = collectFormData();

    // Debug: Log the data being sent to API
    console.log('Creating item with data:', JSON.stringify(formData, null, 2));

    // Must save to API first - QR only generated on success
    if (typeof api === 'undefined') {
      showToast('API not available. Please check your connection.', 'error');
      return;
    }

    const response = await api.createItem(formData);

    if (response.success && response.data) {
      // Use SKU from server response (authoritative)
      const serverData = response.data;

      // Update displayed SKU with server SKU (authoritative)
      document.getElementById('skuValue').textContent = serverData.sku;
      document.getElementById('qrSkuDisplay').textContent = serverData.sku;

      // Generate QR code ONLY after successful save
      generateQRCode(serverData);

      // Upload images if any selected (non-blocking)
      if (selectedPrimaryImage || selectedGalleryImages.length > 0) {
        uploadImages(serverData.sku);
      }

      // Show success state
      showGeneratedState();
      showToast('Item saved to database!', 'success');
    } else {
      // API returned error
      showToast(response.message || 'Failed to save item', 'error');
    }

  } catch (error) {
    console.error('Form submission error:', error);
    showToast('Failed to save item: ' + error.message, 'error');
  } finally {
    submitBtn.classList.remove('loading');
    submitBtn.disabled = false;
  }
}


/**
 * Collect form data for backend API
 * NOTE: SKU and qrData are server-generated, not sent from client
 */
function collectFormData() {
  const name = document.getElementById('itemName').value.trim();
  const categorySelect = document.getElementById('jewelryCategory');
  const categoryId = categorySelect.value;
  const categoryName = categorySelect.options[categorySelect.selectedIndex].text;

  // Get category prefix for server SKU generation
  const prefixMap = {
    'chain': 'CHN',
    'bangles': 'BNG',
    'earrings': 'EAR',
    'necklace': 'NCK',
    'pendant_set': 'PND',
    'others': 'OTH'
  };
  const prefix = prefixMap[categoryId] || categoryId.substring(0, 3).toUpperCase();

  const purity = document.getElementById('goldPurity').value;
  const goldWeight = parseFloat(document.getElementById('goldWeight').value);

  // Collect diamonds (always diamond mode)
  const diamonds = [];
  document.querySelectorAll('#diamondSection .diamond-row').forEach(row => {
    const typeSelect = row.querySelector('.diamond-type');
    const typeId = typeSelect.value;
    const typeName = (typeSelect.selectedIndex >= 0 && typeSelect.options[typeSelect.selectedIndex])
      ? typeSelect.options[typeSelect.selectedIndex].text
      : typeId.charAt(0).toUpperCase() + typeId.slice(1);

    const sourceSelect = row.querySelector('.diamond-source');
    const source = sourceSelect.value;
    const sourceName = (sourceSelect.selectedIndex >= 0 && sourceSelect.options[sourceSelect.selectedIndex])
      ? sourceSelect.options[sourceSelect.selectedIndex].text
      : (source === 'real' ? 'Real (Natural)' : 'CVD (Lab-grown)');

    const weight = parseFloat(row.querySelector('.diamond-weight').value);

    if (typeId && source && weight > 0) {
      diamonds.push({
        type_id: typeId,
        type_name: typeName,
        source: source,
        source_name: sourceName,
        weight_ct: weight
      });
    }
  });

  // Build data - always diamond mode, polkiStones empty
  return {
    name: name || undefined,
    articleType: 'diamond',
    category: {
      id: categoryId,
      name: categoryName,
      prefix: prefix
    },
    gold: {
      purity: purity,
      weight_g: goldWeight
    },
    diamonds: diamonds,
    polkiStones: []
  };
  // NOTE: SKU and qrData will be returned in server response
}


/**
 * Generate QR code
 */
function generateQRCode(data) {
  const qrDiv = document.getElementById('qrCodeDiv');
  qrDiv.innerHTML = ''; // Clear previous QR

  // Encode only the SKU for smaller, cleaner QR codes
  // Item details are fetched from database on scan
  const skuPayload = data.sku;

  new QRCode(qrDiv, {
    text: skuPayload,
    width: 256,
    height: 256,
    colorDark: "#1A2332",
    colorLight: "#FFFFFF",
    correctLevel: QRCode.CorrectLevel.H
  });

  // Update timestamp
  const now = new Date();
  const timestamp = now.toLocaleString('en-US', {
    month: 'short',
    day: 'numeric',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit'
  });
  document.getElementById('timestamp').textContent = `Generated on ${timestamp}`;
}

